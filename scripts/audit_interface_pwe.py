import argparse
import json
from pathlib import Path
import sys
import time
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/"src"))
from invdes.interface_pwe import (
    normal_projector_grid, projector_matrices, factorized_impermittivity, frequencies,
)
from audit_pure_pwe import reciprocal_indices, reciprocal_basis, path_coordinates, eta_matrix, solve


def layered_check(factorization=factorized_impermittivity, frequency_solver=frequencies):
    """Independent analytic bilayer transfer-matrix dispersion, period=1 metre."""
    fraction, kappa = .37, .73*np.pi
    def characteristic(w):
        p, q = w*3*fraction, w*(1-fraction)
        return np.cos(p)*np.cos(q)-.5*(3+1/3)*np.sin(p)*np.sin(q)-np.cos(kappa)
    roots = []
    samples = np.linspace(0, 14, 20001)
    for lo, hi in zip(samples[:-1], samples[1:]):
        if characteristic(lo)*characteristic(hi) < 0:
            for _ in range(45):
                mid = (lo+hi)/2
                if characteristic(lo)*characteristic(mid) <= 0:
                    hi = mid
                else:
                    lo = mid
            roots.append((lo+hi)/2)
    expected = np.array(roots[:4])*299792458/(2*np.pi*1e9)
    runs = []
    for cutoff in [3, 7, 15, 31]:
        ids = np.arange(-cutoff, cutoff+1)
        diff = ids[:, None]-ids[None, :]
        hole = fraction*np.sinc(diff*fraction)*np.exp(-1j*np.pi*diff*fraction)
        identity = np.eye(len(ids))
        eps = identity + 8*hole
        eta = identity - (8/9)*hole
        zero = np.zeros_like(eta)
        tensor = factorization(eta, eps, (identity, zero, zero))
        g = np.column_stack([2*np.pi*ids, np.zeros(len(ids))])
        f, _ = frequency_solver(g, [[kappa, 0]], tensor, 4)
        standard, _ = frequencies(g, [[kappa, 0]], (eta, zero, zero, eta), 4)
        runs.append({"cutoff": cutoff, "factorized_max_relative_error_pct":
                     float(np.max(abs(f[0]-expected)/expected)*100),
                     "direct_max_relative_error_pct":
                     float(np.max(abs(standard[0]-expected)/expected)*100)})
    return {"analytical_first4_GHz": expected.tolist(), "runs": runs}


def save(result):
    out = ROOT/"results/interface_pwe_audit"
    out.mkdir(parents=True, exist_ok=True)
    # Selected-point gaps only; no full-path/zone-gap inference.
    im = result["config"]["path_parameters"].index(1.0)
    ik = result["config"]["path_parameters"].index(2.0)
    for design in result["designs"]:
        for row in design["runs"]:
            f = np.asarray(row["factorized_GHz"])
            fi = np.asarray(row["factorized_imaginary_GHz"])
            row["direct_K_real_GHz"] = float(f[ik, 1]-f[ik, 0])
            row["indirect_M_K_real_GHz"] = float(f[im, 1]-f[ik, 0])
            row["first_two_max_frequency_imaginary_pct"] = float(
                np.max(abs(fi[:, :2])/abs(f[:, :2]))*100)
    (out/"results.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    lines = ["# Interface-aware PWE convergence", "",
             "Generated by scripts/audit_interface_pwe.py. No reference spectra, training, fitting, or COMSOL calls.",
             "", "Model B (normal-vector Fourier factorization): https://arxiv.org/abs/1005.4219 .",
             "Exact boundary-integrated material coefficients; nearest-interface normal extension.",
             "The normal field has medial-axis discontinuities. General complex eigensolves are used without symmetrization.",
             "", "## Analytic layered-medium check", "",
             "|Cutoff|Factorized max error %|Direct max error %|",
             "|---:|---:|---:|"]
    for r in result["layered"]["runs"]:
        lines.append(f'|{r["cutoff"]}|{r["factorized_max_relative_error_pct"]:.8f}|{r["direct_max_relative_error_pct"]:.8f}|')
    lines += ["", "## Geometry-only refinement", "",
              "Frequency changes below use REAL PARTS of the first two bands over all sampled k points.",
              "Complex frequencies are retained explicitly. These runs do not pass physical-realness validation.",
              "They are self-convergence indicators, NOT certified errors or comparisons with COMSOL.",
              "", "|Side multipliers|Cutoff|Direct basis change %|Factorized real-part change %|Max imaginary/real frequency % (six bands)|",
              "|---|---:|---:|---:|---:|"]
    for d in result["designs"]:
        for r in d["runs"]:
            lines.append(f'|{d["side_multipliers"]}|{r["cutoff"]}|{r.get("direct_change_pct", float("nan")):.6f}|{r.get("factorized_change_pct", float("nan")):.6f}|{r["max_frequency_imaginary_pct"]:.8f}|')
    for d in result["designs"]:
        if "normal_grid_change_pct" in d:
            lines += ["", f'Normal-grid doubling change for {d["side_multipliers"]}: {d["normal_grid_change_pct"]:.8f}%.', ""]
    lines += ["", "## Selected-point gap refinement", "",
              "These are real-part diagnostics of the experimental complex spectrum.", "",
              "|Side multipliers|Final direct K GHz|Last-increment change GHz|Final indirect M/K GHz|Last-increment change GHz|",
              "|---|---:|---:|---:|---:|"]
    for d in result["designs"]:
        old, last = d["runs"][-2:]
        direct, indirect = last["direct_K_real_GHz"], last["indirect_M_K_real_GHz"]
        lines.append(f'|{d["side_multipliers"]}|{direct:.6f}|{abs(direct-old["direct_K_real_GHz"]):.6f}|{indirect:.6f}|{abs(indirect-old["indirect_M_K_real_GHz"]):.6f}|')
    lines += ["", "## Scope and limitations", "",
              "Material constants and geometry are fixed physical inputs. No spectral labels are loaded.",
              "This is an experimental NumPy backend, not a replacement for the production Torch backend.",
              "The original direct Galerkin solver is retained as a separate reference.",
              "No finite-basis agreement proves absolute accuracy; basis, normal-grid, and boundary-quadrature errors must be separated.",
              "Selected k points do not establish the full-Brillouin-zone band gap.",
              "No existing project acceptance gate is redefined or claimed to pass.",
              "Production promotion is withheld: complex-frequency artifacts remain.",
              "", "## Reproduce", "",
              "From the Tushar directory, using an environment with NumPy:",
              "```",
              "python tests/test_interface_pwe.py",
              "python scripts/audit_interface_pwe.py",
              "```",
              "Settings are in configs/interface_pwe_audit.json, fixed before the experiment.",
              "No additional dependencies were installed. The full existing project test suite was not run."]
    (out/"REPORT.md").write_text("\n".join(lines)+"\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, default=ROOT/"configs/interface_pwe_audit.json")
    parser.add_argument("--report-only", action="store_true")
    args = parser.parse_args()
    if args.report_only:
        save(json.loads((ROOT/"results/interface_pwe_audit/results.json").read_text()))
        return
    cfg = json.loads(args.config.read_text())
    result = {"config": cfg, "layered": layered_check(), "designs": []}
    a = cfg["a_um"]
    for multipliers in cfg["side_multipliers"]:
        sides = np.array(multipliers)*a/np.sqrt(3)
        samples = normal_projector_grid(a, sides, cfg["normal_grids"][0])
        item = {"side_multipliers": multipliers, "sides_um": sides.tolist(), "runs": []}
        previous = None
        for cutoff in cfg["cutoffs"]:
            start = time.perf_counter()
            ids = reciprocal_indices(cutoff)
            eta = eta_matrix(ids, a, sides, cfg["arc_order"])
            # Binary eps={1,9}: epsilon = 10 I - 9 eta, exact Fourier identity.
            if (cfg["eps_background"], cfg["eps_hole"]) != (9., 1.):
                raise ValueError("Boundary helper currently supports eps={9,1} only")
            eps = 10*np.eye(len(ids))-9*eta
            tensor = factorized_impermittivity(eta, eps, projector_matrices(ids, samples))
            kpoints = path_coordinates(cfg["path_parameters"], a*1e-6)
            g = ids @ reciprocal_basis(a*1e-6)
            complex_f, checks = frequencies(g, kpoints, tensor, cfg["bands"], diagnostic_complex=True)
            f = complex_f.real
            direct = solve(ids, a*1e-6, eta, kpoints, cfg["bands"])
            row = {"cutoff": cutoff, "plane_waves": len(ids), "factorized_GHz": f.tolist(),
                   "direct_GHz": direct.tolist(), "diagnostics": checks,
                   "factorized_imaginary_GHz": complex_f.imag.tolist(),
                   "max_frequency_imaginary_pct": float(np.max(abs(complex_f.imag)/abs(f))*100),
                   "seconds": time.perf_counter()-start}
            if previous is not None:
                row["factorized_change_pct"] = float(np.max(abs(f[:, :2]-previous[0][:, :2])/f[:, :2])*100)
                row["direct_change_pct"] = float(np.max(abs(direct[:, :2]-previous[1][:, :2])/direct[:, :2])*100)
            previous = f, direct
            item["runs"].append(row)
            print(multipliers, cutoff, {k: v for k, v in row.items() if k.endswith("pct") or k == "seconds"}, flush=True)
        refined = normal_projector_grid(a, sides, cfg["normal_grids"][1])
        tensor = factorized_impermittivity(eta, eps, projector_matrices(ids, refined))
        refined_complex, checks = frequencies(g, kpoints, tensor, cfg["bands"], diagnostic_complex=True)
        refined_f = refined_complex.real
        item["refined_normal_grid_GHz"] = refined_f.tolist()
        item["refined_normal_grid_imaginary_GHz"] = refined_complex.imag.tolist()
        item["normal_grid_change_pct"] = float(np.max(abs(refined_f[:, :2]-f[:, :2])/refined_f[:, :2])*100)
        item["refined_diagnostics"] = checks
        result["designs"].append(item)
        save(result)
    print("Saved", ROOT/"results/interface_pwe_audit", flush=True)


if __name__ == "__main__":
    main()
