"""Render compact documentation from saved JSON; no physics or third-party imports."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "forward": "results/energy_pwe_full_validation/results.json",
    "lodo": "results/pure_pwe_inverse_lodo/results.json",
    "multistart": "results/pure_pwe_multistart_v1/verification_summary.json",
    "atlas": "results/pure_pwe_atlas_validation_v1/final/audit_summary.json",
}


def load_sources(root):
    records, hashes = {}, {}
    for name, relative in SOURCES.items():
        raw = (root / relative).read_bytes()
        records[name] = json.loads(raw)
        hashes[relative] = hashlib.sha256(raw).hexdigest()
    return records, hashes


def render(records, hashes):
    f, l, m, a = (records[key] for key in ("forward", "lodo", "multistart", "atlas"))
    p = f["overall_source"]["pointwise"]
    g = f["overall_source"]["bandgap_features"]["path_gap"]
    lines = [
        "# Saved scientific results snapshot", "",
        "Generated by `python scripts/build_repository_snapshot.py` from saved JSON.",
        "This is a transcription with source hashes, not a fresh numerical verification.",
        "Experiments have distinct solvers, datasets and acceptance scopes; do not pool their errors.", "",
        "## Forward comparison", "",
        f"Source: [full-path results](../{SOURCES['forward']}). Status: `{f['status']}`.", "",
        f"Verified structure: `{f['verified_structure']}`; `{f['unverified_structure']}` remains diagnostic.",
        f"Completed geometries: {f['completed_geometries']}/{f['requested_verified_geometries']}; sampled k evaluations: {f['computed_k_points']}.", "",
        "| Quantity | GHz |", "|---|---:|",
        f"| Pointwise MAE | {p['mae_ghz']:.9f} |",
        f"| Pointwise RMSE | {p['rmse_ghz']:.9f} |",
        f"| Pointwise maximum error | {p['max_error_ghz']:.9f} |",
        f"| Signed path-gap MAE | {g['mae_ghz']:.9f} |",
        f"| Signed path-gap maximum error | {g['max_error_ghz']:.9f} |", "",
        "These errors belong to the frozen sampled-normal energy-PWE configuration,",
        "not automatically to the later fixed radial-projector inverse evaluator.", "",
        "## Saved-library inverse benchmark", "",
        f"Source: [positive-gap LODO](../{SOURCES['lodo']}). Status: `{l['status']}`.", "",
        f"Matched {l['matched_cases']} of {l['total_targets']} targets; nonmatches: {l['nonmatching_cases']}; execution errors: {l['execution_errors']}.",
        f"Returned-candidate gap MAE: {l['gap_mae_ghz']:.9f} GHz; maximum error: {l['gap_max_error_ghz']:.9f} GHz.",
        "The nonmatch remains in the benchmark. Lack of a saved bracket does not prove physical unreachability.", "",
        "## Anchor-free multistart experiment", "",
        f"Source: [independent verification](../{SOURCES['multistart']}). Status: `{m['status']}`.", "",
        f"Successful cases: {m['successful_cases']}/{m['case_count']}; targets: {m['target_count']}; starts per target: {m['starts_per_target']}.",
        f"M25 matches: {m['matches_at_M25']}; empirical refinement guard passes: {m['passes_empirical_refinement_guard']}.",
        f"Existing tolerance: {m['existing_tolerance_GHz']:.6f} GHz.",
        "Prescribed finite starts do not establish global convergence or unique geometry recovery.", "",
        "## Atlas-proposed, physics-checked designs", "",
        f"Source: [final audit](../{SOURCES['atlas']}). Status: `{a['status']}`.", "",
        f"Successful cases: {a['successful_cases']}/{len(a['cases'])}; source M20 records: {a['source_M20_count']}.", "",
        "| Target GHz | L1 um | L2 um | M20 gap GHz | M25 gap GHz | M25 absolute error GHz | Accepted |",
        "|---:|---:|---:|---:|---:|---:|---|",
    ]
    for c in a["cases"]:
        lines.append(f"| {c['target_gap_GHz']:.6f} | {c['sides_um'][0]:.9f} | {c['sides_um'][1]:.9f} | "
                     f"{c['gap_M20_GHz']:.9f} | {c['gap_M25_GHz']:.9f} | {c['error_M25_GHz']:.9f} | {c['success']} |")
    lines += ["", "Acceptance checks the unchanged candidate at a higher cutoff. It is not a full-zone or continuum certificate.",
              "The atlas-validation implementation audit was post-launch; see the detailed guide for the provenance limitation.", "",
              "### Recorded timing", "",
              f"New full-path evaluations: {a['distinct_evaluations']} ({a['evaluations_by_cutoff']}); summed evaluation time: {a['evaluation_seconds']/60:.3f} minutes.",
              f"Selecting the complete set of starts took a median {1000*a['proposal_selection_benchmark']['median_seconds']:.3f} ms across {a['proposal_selection_benchmark']['repeats']} repeats.",
              "Proposal timing is not end-to-end validated inverse-design latency. These are historical hardware measurements.", "",
              "### Offline interpolant comparison", "",
              "| Model | Grouped interior samples | MAE GHz | Maximum absolute error GHz |",
              "|---|---:|---:|---:|"]
    for model in a["interpolant_comparison"]["models"]:
        cv = model["grouped_CV_inside_hull"]
        lines.append(f"| {model['name']} | {cv['count']} | {cv['MAE_GHz']:.9f} | {cv['max_absolute_GHz']:.9f} |")
    lines += ["", a["interpolant_comparison"]["limitations"], "",
              "## Source integrity", "",
              "Hashes identify the exact JSON read by this generator; they do not independently certify its contents.", "",
              "| Source | SHA-256 |", "|---|---|"]
    for path, digest in hashes.items():
        lines.append(f"| [{path}](../{path}) | `{digest}` |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the saved document is absent or stale; do not write")
    args = parser.parse_args()
    text = render(*load_sources(ROOT))
    destination = ROOT / "docs/RESULTS_SNAPSHOT.md"
    if args.check:
        if not destination.exists() or destination.read_text(encoding="utf-8") != text:
            raise SystemExit("Results snapshot is missing or stale")
        print("Results snapshot matches saved JSON")
    else:
        destination.write_text(text, encoding="utf-8", newline="\n")
        print(destination)


if __name__ == "__main__":
    main()
